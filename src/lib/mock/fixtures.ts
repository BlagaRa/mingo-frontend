function pad(value: number) {
  return String(value).padStart(2, "0");
}

function dayIso(year: number, monthIndex: number, day: number) {
  return `${year}-${pad(monthIndex + 1)}-${pad(day)}`;
}

/** Sparse evening slots for ~6 months so the booking calendar can page by month. */
function generatePitchSlots(
  pitchId: string,
  start: Date,
  dayCount: number,
  hours: string[],
  weekdays: number[],
  idPrefix: string,
): Slot[] {
  const generated: Slot[] = [];
  let serial = 0;
  for (let offset = 0; offset < dayCount; offset++) {
    const date = new Date(start);
    date.setDate(start.getDate() + offset);
    if (!weekdays.includes(date.getDay())) continue;
    const day = dayIso(date.getFullYear(), date.getMonth(), date.getDate());
    for (const hour of hours) {
      serial += 1;
      const [h, m] = hour.split(":").map(Number);
      const endHour = h + 1;
      generated.push({
        id: `${idPrefix}-${serial}`,
        pitchId,
        startsAt: `${day}T${pad(h)}:${pad(m)}:00+02:00`,
        endsAt: `${day}T${pad(endHour)}:${pad(m)}:00+02:00`,
      });
    }
  }
  return generated;
}

